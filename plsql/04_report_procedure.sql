-- Purpose: Executive & Operational Fraud Detection Summary Report
--          Using DBMS_OUTPUT formatting.
-- ============================================================

CREATE OR REPLACE PROCEDURE proc_generate_fraud_report (
  p_start_date IN DATE DEFAULT NULL,
  p_end_date   IN DATE DEFAULT NULL
) IS
  -- Scope counts
  v_total_cust        NUMBER := 0;
  v_total_acc         NUMBER := 0;
  v_total_txns        NUMBER := 0;
  v_flagged_txns      NUMBER := 0;
  v_fraud_txns        NUMBER := 0;
  v_total_vol         NUMBER := 0;
  v_fraud_vol         NUMBER := 0;

  -- Alert pipeline counts
  v_total_alerts      NUMBER := 0;
  v_open_alerts       NUMBER := 0;
  v_reviewed_alerts   NUMBER := 0;
  v_confirmed_alerts  NUMBER := 0;
  v_false_alarms      NUMBER := 0;

  -- Performance metrics
  v_flag_rate         NUMBER := 0;
  v_fraud_rate        NUMBER := 0;
  v_true_positives    NUMBER := 0;
  v_false_positives   NUMBER := 0;
  v_false_negatives   NUMBER := 0;
  v_precision         NUMBER := 0;
  v_recall            NUMBER := 0;

  -- Date range boundaries
  v_from_date         DATE;
  v_to_date           DATE;
BEGIN
  -- Setup date boundaries
  v_from_date := NVL(p_start_date, TO_DATE('1970-01-01', 'YYYY-MM-DD'));
  v_to_date   := NVL(p_end_date, SYSDATE + 1);

  -- 1. Base counts
  SELECT COUNT(*) INTO v_total_cust FROM customers;
  SELECT COUNT(*) INTO v_total_acc  FROM accounts;

  SELECT
    COUNT(*),
    COUNT(CASE WHEN is_flagged = 'Y' THEN 1 END),
    COUNT(CASE WHEN is_fraud = 'Y' THEN 1 END),
    NVL(SUM(amount), 0),
    NVL(SUM(CASE WHEN is_fraud = 'Y' THEN amount ELSE 0 END), 0)
  INTO
    v_total_txns,
    v_flagged_txns,
    v_fraud_txns,
    v_total_vol,
    v_fraud_vol
  FROM transactions
  WHERE CAST(txn_time AS DATE) BETWEEN v_from_date AND v_to_date;

  -- 2. Alert counts
  SELECT
    COUNT(*),
    COUNT(CASE WHEN status = 'OPEN' THEN 1 END),
    COUNT(CASE WHEN status = 'REVIEWED' THEN 1 END),
    COUNT(CASE WHEN status = 'CONFIRMED_FRAUD' THEN 1 END),
    COUNT(CASE WHEN status = 'FALSE_ALARM' THEN 1 END)
  INTO
    v_total_alerts,
    v_open_alerts,
    v_reviewed_alerts,
    v_confirmed_alerts,
    v_false_alarms
  FROM fraud_alerts fa
  JOIN transactions t ON fa.txn_id = t.txn_id
  WHERE CAST(t.txn_time AS DATE) BETWEEN v_from_date AND v_to_date;

  -- 3. Confusion Matrix metrics against ground-truth
  SELECT
    COUNT(CASE WHEN is_flagged = 'Y' AND is_fraud = 'Y' THEN 1 END),
    COUNT(CASE WHEN is_flagged = 'Y' AND is_fraud = 'N' THEN 1 END),
    COUNT(CASE WHEN is_flagged = 'N' AND is_fraud = 'Y' THEN 1 END)
  INTO
    v_true_positives,
    v_false_positives,
    v_false_negatives
  FROM transactions
  WHERE CAST(txn_time AS DATE) BETWEEN v_from_date AND v_to_date;

  -- Compute rates
  IF v_total_txns > 0 THEN
    v_flag_rate  := ROUND((v_flagged_txns / v_total_txns) * 100, 2);
    v_fraud_rate := ROUND((v_fraud_txns / v_total_txns) * 100, 2);
  END IF;

  IF (v_true_positives + v_false_positives) > 0 THEN
    v_precision := ROUND((v_true_positives / (v_true_positives + v_false_positives)) * 100, 2);
  END IF;

  IF (v_true_positives + v_false_negatives) > 0 THEN
    v_recall := ROUND((v_true_positives / (v_true_positives + v_false_negatives)) * 100, 2);
  END IF;

  -- Output Report Header
  DBMS_OUTPUT.PUT_LINE('========================================================================');
  DBMS_OUTPUT.PUT_LINE('           AI-BASED FRAUD DETECTION SYSTEM - EXECUTIVE REPORT           ');
  DBMS_OUTPUT.PUT_LINE('========================================================================');
  DBMS_OUTPUT.PUT_LINE('Generated On   : ' || TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS'));
  DBMS_OUTPUT.PUT_LINE('Generated By   : ' || USER);
  IF p_start_date IS NOT NULL OR p_end_date IS NOT NULL THEN
    DBMS_OUTPUT.PUT_LINE('Filter Window  : ' || TO_CHAR(v_from_date, 'YYYY-MM-DD') || ' to ' || TO_CHAR(v_to_date, 'YYYY-MM-DD'));
  ELSE
    DBMS_OUTPUT.PUT_LINE('Filter Window  : ALL TIME DATASET');
  END IF;
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 1: Executive KPI Summary
  DBMS_OUTPUT.PUT_LINE('[1] EXECUTIVE SUMMARY & KEY PERFORMANCE INDICATORS');
  DBMS_OUTPUT.PUT_LINE('  - Total Registered Customers   : ' || LPAD(TO_CHAR(v_total_cust), 10));
  DBMS_OUTPUT.PUT_LINE('  - Total Active Accounts        : ' || LPAD(TO_CHAR(v_total_acc), 10));
  DBMS_OUTPUT.PUT_LINE('  - Total Transactions Processed : ' || LPAD(TO_CHAR(v_total_txns), 10));
  DBMS_OUTPUT.PUT_LINE('  - Transactions Flagged         : ' || LPAD(TO_CHAR(v_flagged_txns), 10) || ' (' || v_flag_rate || '%)');
  DBMS_OUTPUT.PUT_LINE('  - Confirmed Frauds (Ground)    : ' || LPAD(TO_CHAR(v_fraud_txns), 10) || ' (' || v_fraud_rate || '%)');
  DBMS_OUTPUT.PUT_LINE('  - Total Transaction Volume     : Rs. ' || TO_CHAR(v_total_vol, 'FM999,999,990.00'));
  DBMS_OUTPUT.PUT_LINE('  - Total Fraud Volume At Risk   : Rs. ' || TO_CHAR(v_fraud_vol, 'FM999,999,990.00'));
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 2: Detection Quality & Accuracy
  DBMS_OUTPUT.PUT_LINE('[2] DETECTION ENGINE PERFORMANCE');
  DBMS_OUTPUT.PUT_LINE('  - True Positives (Flagged & Fraud) : ' || LPAD(TO_CHAR(v_true_positives), 6));
  DBMS_OUTPUT.PUT_LINE('  - False Positives (Flagged Normal) : ' || LPAD(TO_CHAR(v_false_positives), 6));
  DBMS_OUTPUT.PUT_LINE('  - False Negatives (Missed Fraud)   : ' || LPAD(TO_CHAR(v_false_negatives), 6));
  DBMS_OUTPUT.PUT_LINE('  - Rule Precision                   : ' || LPAD(TO_CHAR(v_precision, 'FM990.00') || '%', 8));
  DBMS_OUTPUT.PUT_LINE('  - Rule Recall (Detection Rate)     : ' || LPAD(TO_CHAR(v_recall, 'FM990.00') || '%', 8));
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 3: Alert Resolution Pipeline
  DBMS_OUTPUT.PUT_LINE('[3] FRAUD ALERT INVESTIGATION PIPELINE');
  DBMS_OUTPUT.PUT_LINE('  - Total Alerts Raised          : ' || LPAD(TO_CHAR(v_total_alerts), 10));
  DBMS_OUTPUT.PUT_LINE('  - OPEN (Action Required)       : ' || LPAD(TO_CHAR(v_open_alerts), 10));
  DBMS_OUTPUT.PUT_LINE('  - Under Investigation/Reviewed : ' || LPAD(TO_CHAR(v_reviewed_alerts), 10));
  DBMS_OUTPUT.PUT_LINE('  - Confirmed Fraudulent         : ' || LPAD(TO_CHAR(v_confirmed_alerts), 10));
  DBMS_OUTPUT.PUT_LINE('  - Closed as False Alarms       : ' || LPAD(TO_CHAR(v_false_alarms), 10));
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 4: Channel Breakdown
  DBMS_OUTPUT.PUT_LINE('[4] BREAKDOWN BY TRANSACTION CHANNEL');
  DBMS_OUTPUT.PUT_LINE(RPAD('Channel', 10) || RPAD('Txns', 10) || RPAD('Flagged', 10) || RPAD('Fraud', 10) || RPAD('Fraud Rate', 12) || 'Volume (Rs.)');
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');
  FOR ch IN (
    SELECT
      channel,
      COUNT(*) AS n_txns,
      COUNT(CASE WHEN is_flagged = 'Y' THEN 1 END) AS n_flagged,
      COUNT(CASE WHEN is_fraud = 'Y' THEN 1 END) AS n_fraud,
      ROUND(SUM(amount), 2) AS total_amt
    FROM transactions
    WHERE CAST(txn_time AS DATE) BETWEEN v_from_date AND v_to_date
    GROUP BY channel
    ORDER BY n_fraud DESC, channel
  ) LOOP
    DBMS_OUTPUT.PUT_LINE(
      RPAD(NVL(ch.channel, 'UNKNOWN'), 10) ||
      RPAD(TO_CHAR(ch.n_txns), 10) ||
      RPAD(TO_CHAR(ch.n_flagged), 10) ||
      RPAD(TO_CHAR(ch.n_fraud), 10) ||
      RPAD(TO_CHAR(ROUND((ch.n_fraud / ch.n_txns) * 100, 1), 'FM990.0') || '%', 12) ||
      TO_CHAR(ch.total_amt, 'FM999,999,990.00')
    );
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 5: Top High-Risk Customers
  DBMS_OUTPUT.PUT_LINE('[5] TOP HIGH-RISK CUSTOMER ACCOUNTS');
  DBMS_OUTPUT.PUT_LINE(RPAD('Cust ID', 9) || RPAD('Name', 22) || RPAD('Tier', 10) || RPAD('Flagged', 9) || 'Fraud Amt (Rs.)');
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');
  FOR c IN (
    SELECT *
    FROM (
      SELECT
        c.customer_id,
        c.full_name,
        COUNT(CASE WHEN t.is_flagged = 'Y' THEN 1 END) AS flagged_count,
        NVL(SUM(CASE WHEN t.is_fraud = 'Y' THEN t.amount ELSE 0 END), 0) AS fraud_amount,
        CASE
          WHEN COUNT(CASE WHEN t.is_fraud = 'Y' THEN 1 END) > 0 THEN 'CRITICAL'
          WHEN COUNT(CASE WHEN t.is_flagged = 'Y' THEN 1 END) > 1 THEN 'HIGH'
          WHEN COUNT(CASE WHEN t.is_flagged = 'Y' THEN 1 END) = 1 THEN 'MEDIUM'
          ELSE 'LOW'
        END AS risk_tier
      FROM customers c
      JOIN accounts a ON c.customer_id = a.customer_id
      JOIN transactions t ON a.account_id = t.account_id
      WHERE CAST(t.txn_time AS DATE) BETWEEN v_from_date AND v_to_date
      GROUP BY c.customer_id, c.full_name
      ORDER BY fraud_amount DESC, flagged_count DESC
    )
    WHERE ROWNUM <= 5
  ) LOOP
    DBMS_OUTPUT.PUT_LINE(
      RPAD(TO_CHAR(c.customer_id), 9) ||
      RPAD(SUBSTR(c.full_name, 1, 20), 22) ||
      RPAD(c.risk_tier, 10) ||
      RPAD(TO_CHAR(c.flagged_count), 9) ||
      TO_CHAR(c.fraud_amount, 'FM999,999,990.00')
    );
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');

  -- Section 6: Top Suspicious Locations
  DBMS_OUTPUT.PUT_LINE('[6] GEOGRAPHIC FRAUD HOTSPOTS');
  DBMS_OUTPUT.PUT_LINE(RPAD('Location', 15) || RPAD('Type', 10) || RPAD('Txns', 8) || RPAD('Frauds', 8) || 'Fraud Volume (Rs.)');
  DBMS_OUTPUT.PUT_LINE('------------------------------------------------------------------------');
  FOR loc IN (
    SELECT *
    FROM (
      SELECT
        location,
        CASE 
          WHEN UPPER(location) IN ('LAGOS','MOSCOW','DUBAI','SINGAPORE','BUCHAREST','MANILA') THEN 'FOREIGN'
          ELSE 'DOMESTIC'
        END AS loc_type,
        COUNT(*) AS txns,
        COUNT(CASE WHEN is_fraud = 'Y' THEN 1 END) AS frauds,
        NVL(SUM(CASE WHEN is_fraud = 'Y' THEN amount ELSE 0 END), 0) AS fraud_vol
      FROM transactions
      WHERE CAST(txn_time AS DATE) BETWEEN v_from_date AND v_to_date
      GROUP BY location
      ORDER BY frauds DESC, fraud_vol DESC
    )
    WHERE frauds > 0 OR ROWNUM <= 5
  ) LOOP
    DBMS_OUTPUT.PUT_LINE(
      RPAD(loc.location, 15) ||
      RPAD(loc.loc_type, 10) ||
      RPAD(TO_CHAR(loc.txns), 8) ||
      RPAD(TO_CHAR(loc.frauds), 8) ||
      TO_CHAR(loc.fraud_vol, 'FM999,999,990.00')
    );
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('========================================================================');
  DBMS_OUTPUT.PUT_LINE('                     END OF FRAUD DETECTION REPORT                      ');
  DBMS_OUTPUT.PUT_LINE('========================================================================');
END proc_generate_fraud_report;
