-- Clean re-run: drop old tables if they exist
BEGIN
  FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
              'ALERT_AUDIT_LOG','FRAUD_ALERTS','TRANSACTIONS','ACCOUNTS','CUSTOMERS'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS';
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
/

CREATE TABLE customers (
  customer_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(100) NOT NULL,
  email         VARCHAR2(100),
  city          VARCHAR2(50),
  created_date  DATE DEFAULT SYSDATE
);

CREATE TABLE accounts (
  account_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  customer_id   NUMBER NOT NULL,
  account_type  VARCHAR2(20) DEFAULT 'SAVINGS'
                CHECK (account_type IN ('SAVINGS','CURRENT')),
  balance       NUMBER(14,2) DEFAULT 0,
  opened_date   DATE DEFAULT SYSDATE,
  CONSTRAINT fk_acc_cust FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
);

CREATE TABLE transactions (
  txn_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  account_id     NUMBER NOT NULL,
  amount         NUMBER(12,2) NOT NULL CHECK (amount > 0),
  txn_time       TIMESTAMP DEFAULT SYSTIMESTAMP,
  merchant       VARCHAR2(100),
  location       VARCHAR2(100),
  channel        VARCHAR2(20) CHECK (channel IN ('POS','ONLINE','ATM','UPI')),
  is_flagged     CHAR(1) DEFAULT 'N' CHECK (is_flagged IN ('Y','N')),  -- set by PL/SQL (Person 2)
  anomaly_score  NUMBER(6,4),                                          -- written by ML (Person 3)
  is_fraud       CHAR(1) DEFAULT 'N' CHECK (is_fraud IN ('Y','N')),    -- true label, for evaluating ML
  CONSTRAINT fk_txn_acc FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);

CREATE TABLE fraud_alerts (
  alert_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  txn_id        NUMBER NOT NULL,
  alert_reason  VARCHAR2(200),
  alert_time    TIMESTAMP DEFAULT SYSTIMESTAMP,
  status        VARCHAR2(20) DEFAULT 'OPEN'
                CHECK (status IN ('OPEN','REVIEWED','CONFIRMED_FRAUD','FALSE_ALARM')),
  CONSTRAINT fk_alert_txn FOREIGN KEY (txn_id) REFERENCES transactions(txn_id)
);

CREATE TABLE alert_audit_log (
  log_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  alert_id      NUMBER NOT NULL,
  action        VARCHAR2(50),
  action_time   TIMESTAMP DEFAULT SYSTIMESTAMP,
  performed_by  VARCHAR2(50),
  CONSTRAINT fk_log_alert FOREIGN KEY (alert_id) REFERENCES fraud_alerts(alert_id)
);

-- Indexes for the common lookups (per-account history, time windows, alert joins)
CREATE INDEX idx_txn_account ON transactions(account_id);
CREATE INDEX idx_txn_time    ON transactions(txn_time);
CREATE INDEX idx_acc_cust    ON accounts(customer_id);
CREATE INDEX idx_alert_txn   ON fraud_alerts(txn_id);

